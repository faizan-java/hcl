CREATE TABLE users (
 id VARCHAR2(80) PRIMARY KEY,
 name VARCHAR2(100) NOT NULL,
 email VARCHAR2(254) NOT NULL UNIQUE,
 role VARCHAR2(16) NOT NULL CHECK (role IN ('Patient','Provider','Admin')),
 password_hash VARCHAR2(100) NOT NULL,
 created_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE TABLE appointments (
 id VARCHAR2(80) PRIMARY KEY,
 patient_id VARCHAR2(80) NOT NULL REFERENCES users(id),
 provider_id VARCHAR2(80) NOT NULL REFERENCES users(id),
 specialty VARCHAR2(80) NOT NULL,
 starts_at TIMESTAMP WITH TIME ZONE NOT NULL,
 status VARCHAR2(16) DEFAULT 'Pending' NOT NULL CHECK (status IN ('Pending','Confirmed','Cancelled','Completed')),
 location VARCHAR2(160) DEFAULT 'Northstar Medical Center' NOT NULL,
 created_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL
);
CREATE INDEX appointments_patient_idx ON appointments(patient_id,starts_at);
CREATE INDEX appointments_provider_idx ON appointments(provider_id,starts_at);

CREATE TABLE medications (
 id VARCHAR2(80) PRIMARY KEY, patient_id VARCHAR2(80) NOT NULL REFERENCES users(id),
 name VARCHAR2(120) NOT NULL, dosage VARCHAR2(80) NOT NULL,
 instructions VARCHAR2(500) DEFAULT '' NOT NULL, active NUMBER(1) DEFAULT 1 NOT NULL CHECK(active IN (0,1))
);
CREATE TABLE health_records (
 id VARCHAR2(80) PRIMARY KEY, patient_id VARCHAR2(80) NOT NULL REFERENCES users(id),
 provider_id VARCHAR2(80) NOT NULL REFERENCES users(id), title VARCHAR2(120) NOT NULL,
 summary VARCHAR2(4000) NOT NULL, recorded_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL
);
CREATE TABLE invoices (
 id VARCHAR2(80) PRIMARY KEY, patient_id VARCHAR2(80) NOT NULL REFERENCES users(id),
 invoice_number VARCHAR2(32) NOT NULL UNIQUE, description VARCHAR2(250) NOT NULL,
 amount_cents NUMBER(12) NOT NULL CHECK(amount_cents>=0),
 status VARCHAR2(16) NOT NULL CHECK(status IN ('Open','Paid','Overdue')), due_at DATE NOT NULL,
 created_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL
);
CREATE TABLE vitals (
 id VARCHAR2(80) PRIMARY KEY, patient_id VARCHAR2(80) NOT NULL REFERENCES users(id),
 metric VARCHAR2(100) NOT NULL, vital_value BINARY_DOUBLE NOT NULL, unit VARCHAR2(32) NOT NULL,
 range_status VARCHAR2(24) DEFAULT 'Normal' NOT NULL,
 recorded_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL
);
CREATE TABLE patient_body_complaints (
 id VARCHAR2(80) PRIMARY KEY, patient_id VARCHAR2(80) NOT NULL REFERENCES users(id),
 body_part VARCHAR2(120) NOT NULL, body_part_id VARCHAR2(80) NOT NULL, symptom VARCHAR2(120) NOT NULL,
 pain_level NUMBER(2) NOT NULL CHECK(pain_level BETWEEN 1 AND 10), duration VARCHAR2(80) NOT NULL,
 description VARCHAR2(2000) DEFAULT '' NOT NULL, diagnosis VARCHAR2(1200) DEFAULT '' NOT NULL,
 doctor_notes VARCHAR2(3000) DEFAULT '' NOT NULL,
 treatment_recommendation VARCHAR2(2000) DEFAULT '' NOT NULL,
 status VARCHAR2(20) DEFAULT 'Open' NOT NULL CHECK(status IN ('Open','Under Review','Resolved')),
 created_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
 updated_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL
);
CREATE INDEX body_complaints_patient_idx ON patient_body_complaints(patient_id,created_at);
CREATE TABLE audit_log (
 id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
 actor_id VARCHAR2(80), action VARCHAR2(100) NOT NULL, entity VARCHAR2(100) NOT NULL,
 entity_id VARCHAR2(80), created_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL
);
